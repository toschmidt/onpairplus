#!/usr/bin/env python3
"""Generate the OpenAI100kPatched token-dictionary translation unit for the tokenizer baseline.

token-vldb2026 embeds the dictionary via C23 #embed, which Apple clang does not support yet;
this script emits the same arrays as plain hex initializer lists instead.

(c) 2026 Tobias Schmidt, Nicolas Schmitt - MIT License
"""

import sys
from pathlib import Path


def hexdump(data: bytes) -> str:
    lines = []
    for offset in range(0, len(data), 32):
        lines.append(",".join(f"0x{b:02x}" for b in data[offset:offset + 32]) + ",")
    return "\n".join(lines)


def main() -> None:
    tokens_dir, output = Path(sys.argv[1]), Path(sys.argv[2])
    lengths = (tokens_dir / "openai100kpatched_lengths.bin").read_bytes()
    dictionary = (tokens_dir / "openai100kpatched_dict.bin").read_bytes()
    output.write_text(f"""#include "tokens/openai100kpatched/openai100kpatched.hpp"
// Generated by tokenizer_gen.py - #embed replacement, do not edit
namespace sgtt::tokenizer::openai100kpatched {{
const std::array<uint8_t, {len(lengths)}> token_lengths = {{
{hexdump(lengths)}
}};
alignas(64) const std::array<uint8_t, {len(dictionary)}> token_dict = {{
{hexdump(dictionary)}
}};
}}
""")


if __name__ == "__main__":
    main()
